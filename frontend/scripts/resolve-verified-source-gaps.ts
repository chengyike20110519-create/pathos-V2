const requestedSourceIds = new Set(
  (process.env.RESOLVE_SOURCE_IDS ?? "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean),
);
const selectedVerified = requestedSourceIds.size
  ? VERIFIED.filter((item) => requestedSourceIds.has(item.sourceId))
  : VERIFIED;

function hash(value: string): string {
  return createHash("sha256").update(value).digest("hex").slice(0, 24);
}

async function main(): Promise<void> {
  const client = new pg.Client({ connectionString, ssl: { rejectUnauthorized: false } });
  await client.connect();
  await client.query("BEGIN");
  try {
    const row = await client.query<{ payload: { sources?: Array<Record<string, unknown>> } }>(
      "SELECT payload FROM source_index WHERE id=1 FOR UPDATE",
    );
    const payload = row.rows[0]?.payload ?? { sources: [] };
    const sources = Array.isArray(payload.sources) ? [...payload.sources] : [];
    const byId = new Map(sources.map((source) => [String(source.sourceId ?? ""), source]));
    for (const item of selectedVerified) {
      byId.set(item.sourceId, {
        universityId: item.universityId,
        publisher: item.publisher,
        referenceYear: 2026,
        scope: [],
        sourceId: item.sourceId,
        sourceType: "university_official_catalog",
        status: "verified",
        url: item.url,
      });
      const sourceDbId = `official-source-${hash(item.url)}`;
      const documentId = `official-document-${hash(item.url)}`;
      await client.query(
        `INSERT INTO sources
          (id, name, url, authority, source_type, publisher, parser_name,
           robots_review_status, terms_review_status, fetch_enabled)
         VALUES ($1,$2,$3,'A','official_html',$4,'manual-official-verification',
                 'pending','pending',FALSE)
         ON CONFLICT (id) DO UPDATE SET name=EXCLUDED.name, url=EXCLUDED.url,
           publisher=EXCLUDED.publisher, updated_at=NOW()`,
        [sourceDbId, `${item.publisher} — ${item.sourceId}`, item.url, item.publisher],
      );
      await client.query(
        `INSERT INTO source_documents
          (id, source_id, url, fetch_status, fetch_outcome, error_code,
           error_message, parser_metadata)
         VALUES ($1,$2,$3,'blocked','blocked','MANUAL_URL_VERIFICATION',
           'URL verified from the official institution page; automated fetch remains disabled.',$4::jsonb)
         ON CONFLICT (id) DO UPDATE SET url=EXCLUDED.url,
           parser_metadata=EXCLUDED.parser_metadata`,
        [documentId, sourceDbId, item.url, JSON.stringify({ verifiedBy: "official-page-review", verifiedOn: "2026-10-20" })],
      );
      await client.query(
        `UPDATE source_reference_gaps
            SET status='resolved', reason=$3, metadata=$4::jsonb, updated_at=NOW()
          WHERE university_id=$1 AND source_id=$2`,
        [item.universityId, item.sourceId, "Official source URL verified and registered in source_index.", JSON.stringify({ url: item.url, status: "verified" })],
      );
    }
    await client.query(
      `UPDATE source_index SET payload=$1::jsonb, updated_at=NOW() WHERE id=1`,
      [JSON.stringify({ ...payload, sources: [...byId.values()] })],
    );
    await client.query("COMMIT");
    console.log(JSON.stringify({ ok: true, resolved: selectedVerified.length, sourceIndexEntries: byId.size }, null, 2));
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    await client.end();
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
